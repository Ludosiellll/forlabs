_BANNED_RE = [(re.compile(p, re.IGNORECASE), s) for p, s in BANNED]
_CLICHE_RE = [(re.compile(p, re.IGNORECASE), s) for p, s in CLICHES]


def _finding(rule: str, msg: str, location: str, text: str, suggestion: str | None) -> Finding:
    return Finding(stage="antiai", rule_id=rule, severity="error", location=location, text=text,
                   message=msg, suggestion=suggestion)


def scan_text(text: str, location: str) -> list[Finding]:
    out: list[Finding] = []
    for rx, sug in _BANNED_RE:
        m = rx.search(text)
        if m:
            out.append(_finding("ai.banned", f"Запрещённое слово «{m.group(0)}»", location, text, sug))
    for rx, sug in _CLICHE_RE:
        m = rx.search(text)
        if m:
            out.append(_finding("ai.cliche", f"ИИ-штамп «{m.group(0).strip()}»", location, text, sug))
    return out


_WORD = re.compile(r"[А-Яа-яЁёA-Za-z]+")


def scan_paragraph_openings(paragraphs: list[str], location: str = "Отчёт") -> list[Finding]:
    openings = []
    for p in paragraphs:
        words = _WORD.findall(p.lower())
        if len(words) >= 2:
            openings.append(" ".join(words[:2]))
    out = []
    for opening, count in Counter(openings).items():
        if count >= 3:
            out.append(_finding("ai.same_opening", f"{count} абзаца начинаются одинаково: «{opening}…»",
                                location, opening, "начинать абзацы по-разному"))
    return out
